def renewal_check(model, state, tolerance=1e-9):
    if model.get('original_dimension') != 4:
        return dict(status='NOT_APPLICABLE')
    space = model['space']; groups = [i for i, g in enumerate(space.groups) if space.charges[g[0]] == 1]
    if len(groups) != 1:
        return dict(status='UNRESOLVED_EXCITATION_BLOCK')
    group = groups[0]; lo, hi = space.offsets[group:group+2]
    # Injection state is generated by the physical source from the empty state.
    C = dict(model['jumps'])['source_0']; empty = np.flatnonzero(space.charges == 0)
    if len(empty) != 1:
        return dict(status='UNRESOLVED_EMPTY_BRANCH')
    rho0 = np.zeros((space.d, space.d), complex); rho0[empty[0], empty[0]] = 1.
    injection = C@rho0@C.getH(); P = float(np.trace(injection).real)
    b = space.pack(injection/P)[lo:hi]; K = model['L'][lo:hi, lo:hi]
    try:
        R = splu(K.tocsc()).solve(-b)
    except RuntimeError:
        return dict(status='DARK_OR_SINGULAR_BLOCK_REQUIRES_BRANCH_ANALYSIS')
    full_R = np.zeros(space.size, complex); full_R[lo:hi] = R
    tau = float(space.trace(full_R).real)
    if tau <= 0 or maxabs(K@R+b) > tolerance:
        return dict(status='INVALID_RENEWAL_SOLUTION')
    predicted = P*full_R/(1+P*tau)
    ground = np.zeros((space.d, space.d), complex); ground[empty[0], empty[0]] = 1/(1+P*tau)
    predicted += space.pack(ground)
    error = maxabs(predicted-state)
    return dict(status='PASS' if error <= tolerance else 'FAIL', tau=tau, P_tau=P*tau,
                predicted_F=P/(1+P*tau), predicted_F_over_p_e=1/tau, state_error_inf=error)


def symmetry_check(model, tolerance=1e-12):
    """Test W K relating epsilon and -epsilon at Phi=pi/2, before using parity."""
    if model['space'].d != 216 or abs(model['case']['phi_over_pi']-.5) > 1e-12:
        return dict(symmetry_applicable=False, operator_covariance_residual=None,
                    parity_residual_max=None, parity_tolerance=None, parity_status='NOT_APPLICABLE')
    edges = np.array(list(np.ndindex(3, 3, 3)))
    diagonal = np.array([(-1.)**(((node >> 1) & 1)+sum(edge == 2)) for node in range(8) for edge in edges])
    W = sp.diags(diagonal); H = model['H']; epsilon = model['case']['epsilon']
    err = maxabs((H-2*epsilon*model['n'][1])+W@H.conjugate()@W)
    for _, C in model['jumps']:
        transformed = W@C.conjugate()@W
        # All declared jumps transform up to a real sign in this convention.
        err = max(err, min(maxabs(transformed-C), maxabs(transformed+C)))
    P = model['observables']['P_m6_N2']; J = model['observables']['h6']
    err = max(err, maxabs(W@P.conjugate()@W-P), maxabs(W@J.conjugate()@W-J))
    return dict(symmetry_applicable=err <= tolerance, operator_covariance_residual=err,
                parity_residual_max=None, parity_tolerance=None,
                parity_status='OPERATOR_CHECK_PASSED_STATE_PAIRS_PENDING' if err <= tolerance else 'OPERATOR_CHECK_FAILED')


def f2_differences(records, baseline):
    # Baseline is a pinned, previously verified report of undeformed cases.
    from .plan import full_physical_key
    refs = {}
    for r in baseline['records']:
        if r['case'].get('m6_v_over_J') != 1.:
            raise ValueError('Baseline must contain only undeformed cases')
        key = full_physical_key(r['case'])
        if r.get('physical_key') != key:
            raise ValueError('Baseline lacks matching complete physical fingerprint')
        if key in refs:
            raise ValueError('Duplicate baseline physical case')
        refs[key] = r
    if baseline.get('status') != 'VERIFIED_GITHUB':
        raise ValueError('Unverified baseline')
    out = []
    for record in records:
        c = record['case']; key = full_physical_key(c, undeformed=True)
        if key not in refs:
            raise ValueError('F2 lacks matching baseline')
        base = refs[key]; changes = {name: record['raw'][name]-base['raw'][name] for name in ('J_h', 'h6', 'P_m6_N2')}
        for name in ('J_h', 'h6', 'P_m6_N2'):
            a_u, b_u = record.get('primitive_uncertainty', {}).get(name), base.get('primitive_uncertainty', {}).get(name)
            changes[name+'_uncertainty'] = None if a_u is None or b_u is None else a_u+b_u
        a, b = record['conditional']['j6'], base['conditional']['j6']
        changes['j6'] = None if a['value'] is None or b['value'] is None else a['value']-b['value']
        changes['j6_uncertainty'] = None if a['uncertainty'] is None or b['uncertainty'] is None else a['uncertainty']+b['uncertainty']
        out.append(dict(id=record['id'], baseline_id=base['id'], changes=changes))
    return out


def measured_symmetries(records, responses):
    groups = {}; results = []
    for r in records:
        c = r['case']
        if not r.get('symmetry', {}).get('symmetry_applicable'):
            continue
        key = (c['model'], c['phi_over_pi'], c['node_noise'], c['m6_v_over_J'])
        groups.setdefault(key, {})[float(c['epsilon'])] = r
    for key, line in groups.items():
        for eps in sorted(e for e in line if e > 0 and -e in line):
            a, b = line[eps], line[-eps]
            for name in ('J_h', 'h6', 'P_m6_N2'):
                error = abs(a['raw'][name]-b['raw'][name])
                limit = a['primitive_uncertainty'][name]+b['primitive_uncertainty'][name]
                results.append(dict(kind='antiunitary_parity', cases=[a['id'], b['id']], observable=name,
                                    error=float(error), tolerance=float(limit), status='PASS' if error <= limit else 'FAIL'))
    freq = {}
    for r in responses:
        if r['kind'] == 'frequency':
            freq.setdefault(r['base_id'], {})[r['omega']] = r
    for case, line in freq.items():
        if -.5 not in line or .5 not in line:
            continue
        a, b = line[.5], line[-.5]
        for name in ('J_h', 'K', 'P_m6_N2', 'j6'):
            if a['values'].get(name) is None or b['values'].get(name) is None:
                continue
            error = abs(a['values'][name]-np.conj(b['values'][name]))
            limit = a['uncertainty'][name]+b['uncertainty'][name]
            results.append(dict(kind='frequency_conjugacy', cases=[case], observable=name,
                                error=float(error), tolerance=float(limit), status='PASS' if error <= limit else 'FAIL'))
    return results


def evaluate_predictions(predictions, records, differences):
    """Numerical verdict only when the requested metric and error are resolved."""
    records = {r['id']: r for r in records}; diffs = {r['id']: r for r in differences}; out = []
    for p in predictions['predictions']:
        result = dict(prediction_id=p['prediction_id'], status='EXPLORATORY')
        if p['confirmatory_or_exploratory'] == 'exploratory':
            out.append(result); continue
        definition = p['observable_definition']; name = definition['observable']; terms = definition['linear_terms']
        value = 0.; uncertainty = 0.; unresolved = False; missing_error = False
        for term in terms:
            case_id = term['case_id']; coefficient = float(term['coefficient']); r = records[case_id]
            if definition['kind'] == 'baseline_difference':
                d = diffs[case_id]['changes']; v = d.get(name); u = d.get(name+'_uncertainty')
            elif name in r['conditional']:
                v, u = r['conditional'][name]['value'], r['conditional'][name]['uncertainty']
            else:
                v = r['raw'].get(name); u = r.get('primitive_uncertainty', {}).get(name)
            if v is None:
                unresolved = True; continue
            value += coefficient*v
            if u is None:
                missing_error = True
            else:
                uncertainty += abs(coefficient)*u
        result.update(value=None if unresolved else float(value), uncertainty=None if missing_error else float(uncertainty))
        if unresolved or missing_error:
            result['status'] = 'NUMERICALLY_UNRESOLVED'; out.append(result); continue
        tol = p['tolerance_and_error_rule']['absolute_tolerance']; expected = p['expected_value_or_sign_or_interval']
        if p['prediction_type'] == 'value':
            lower, upper = float(expected)-tol, float(expected)+tol
        elif p['prediction_type'] == 'interval':
            lower, upper = float(expected[0])-tol, float(expected[1])+tol
        else:
            lower, upper = (tol, np.inf) if expected == 1 else (-np.inf, -tol)
        a, b = value-uncertainty, value+uncertainty
        result['status'] = 'SUPPORTED_WITHIN_DECLARED_TOLERANCE' if a >= lower and b <= upper else ('PREDICTION_FAILED' if b < lower or a > upper else 'NUMERICALLY_UNRESOLVED')
        out.append(result)
    return out
