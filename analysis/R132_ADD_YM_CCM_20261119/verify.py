ENGINE = BASE / "ADD_NEIGHBOR_SYNTHESIS_20261117" / "verify.py"
EPS = (1, -1)


def load_engine():
    digest = sha256(ENGINE.read_bytes()).hexdigest()
    assert digest == "d46a47443e610ffe42a0160aaae0487e6c0a9be9e6b96bf72ce39962cf7cf9a1"
    spec = spec_from_file_location("r130", ENGINE)
    engine = module_from_spec(spec)
    spec.loader.exec_module(engine)
    return engine, digest


def pack(a, b):
    return (a & 1) + 2 * (b & 1) + 2 * (a & 2) + 4 * (b & 2)


def label_algebras(engine):
    labels = tuple(range(16))
    reversal = engine.word(engine.r2(engine.named(labels)))
    fixed = [s for s in labels if reversal[s] == s]
    pairs = [(s, reversal[s]) for s in labels if s < reversal[s]]
    assert fixed == [0, 6, 9, 15] and len(pairs) == 6
    assert all(reversal[reversal[s]] == s for s in labels)
    # Matrix units generated by P_i and P_i R P_j.
    units = {(s, s) for s in labels} | {(reversal[s], s) for s in labels}
    assert all((i, l) in units for i, j in units for k, l in units if j == k)
    assert (1, 8) in units and (8, 1) in units and len(units) == 28
    # Q sorts the two port tuples independently, up to exchanging the port roles.
    splits = {s: engine.word(engine.interact(engine.named((s,)), EPS)) for s in labels}
    splits = {s: t for s, t in splits.items() if len(t) == 2}
    survivors = []
    for swap in (False, True):
        accepted = []
        for f, g in product(permutations(range(4)), repeat=2):
            p = list(labels)
            for a, b in product(range(4), repeat=2):
                p[pack(a, b)] = pack(f[b], g[a]) if swap else pack(f[a], g[b])
            if all(splits.get(p[s]) == (p[x], p[y]) for s, (x, y) in splits.items()):
                accepted.append(tuple(p))
        assert accepted == [reversal if swap else labels]
        survivors.append(len(accepted))
    control = np.eye(3, dtype=int)
    cycle = np.roll(control, 1, axis=0)
    assert not np.array_equal(cycle @ cycle, control)
    assert sy.Matrix([list(m.flat) for m in (control, cycle, cycle @ cycle)]).rank() == 3
    return {"three_cycle_control_complex_polynomial_dimension": 3, "fixed": fixed, "two_element_label_orbits": pairs, "joint_complex_dimension": len(units),
            "center_complex_dimension": len(fixed) + len(pairs), "max_simple_block_size": 2,
            "permutations_checked_per_transport_convention": 576,
            "commuting_and_transport_reversing_survivors": survivors}


def charges(w):
    total = [0] * 6
    for s in w:
        a, b, c, d = [(s >> k) & 1 for k in range(4)]
        total = [x + y for x, y in zip(total, (a, b, c, d, a*c, b*d))]
    return total


def charge_classification(engine):
    rows = set()
    for n in (1, 2):
        for w in product(range(16), repeat=n):
            after = engine.word(engine.forward(engine.named(w), EPS))
            assert charges(w) == charges(after)
            delta = Counter(after)
            delta.subtract(w)
            rows.add(tuple(delta[s] for s in range(16)))
    rank = sy.polys.matrices.DomainMatrix.from_Matrix(sy.Matrix(sorted(rows))).rank()
    basis = sy.Matrix([charges((s,)) for s in range(16)])
    assert rank == 10 and basis.rank() == 6 and sy.Matrix(sorted(rows))*basis == sy.zeros(len(rows), 6)
    return {"input_words": 272, "constraint_rank_over_Q": rank, "kernel_dimension": 16-rank}


def graph_operators(length):
    identity = np.eye(length, dtype=int)
    shift = np.roll(identity, 1, axis=1)
    d = shift - identity
    zero = np.zeros_like(d)
    return np.block([[zero, d.T], [d, zero]])


def edge_forms(length):
    D = graph_operators(length)
    indices = np.arange(length)
    projectors = [np.diag(np.tile(indices == i, 2).astype(int)) for i in indices]
    forms = [a @ (D @ b - b @ D) for a, b in product(projectors, repeat=2)]
    def rank(matrices):
        return int(sy.Matrix([list(m.flatten()) for m in matrices]).rank())
    lower = rank([m[length:, :length] for m in forms])
    full = rank(forms)
    assert (lower, full) == (length, 2*length)
    return {"directed_edges": length, "lower_block_rank": lower, "full_one_form_rank": full}


def grading_control(length):
    # J interchanges the left/right labels, including (i,i) on vertices.
    requested = {(i, i) for i in range(length)}
    directed = [(i, (i+1) % length) for i in range(length)]
    edges = directed + [(j, i) for i, j in directed]
    assert not requested.intersection(edges)
    indices = {e: i+length for i, e in enumerate(edges)}
    n = length + len(edges)
    k = np.zeros((n, n), dtype=int)
    k[:length, :length] = np.eye(length, dtype=int)
    for (i, j), index in indices.items():
        k[indices[j, i], index] = -1
    gamma = np.diag([1]*length + [-1]*len(edges))
    assert np.array_equal(k @ k, np.eye(n, dtype=int))
    assert np.array_equal(k @ gamma, gamma @ k)
    return {"directed_odd_diagonal_bimodule_slots": len(requested.intersection(directed)),
            "bidirected_grade_dimensions": [length, len(edges)],
            "bidirected_edge_reversal_grading_sign": 1}


def h(x):
    x = abs(x)
    q = exp(-x)
    return log1p(q) + x*q/(1+q)


def spectral_entropy(length, beta):
    return 2*sum(h(2*beta*sin(pi*k/length)) for k in range(length))


def fock_check():
    levels = np.abs(np.linalg.eigvalsh(graph_operators(6)))
    assert np.allclose(sorted(levels), [0, 0] + [1]*4 + [sqrt(3)]*4 + [2]*2)
    many = np.array([0.0])
    for eps in levels:
        many = np.concatenate((many, many + eps))
    result = []
    for beta in (0, 0.25, 1, 4):
        weights = np.exp(-beta*many)
        prob = weights/weights.sum()
        entropy = float(-prob @ np.log(prob))
        predicted = spectral_entropy(6, beta)
        assert abs(entropy-predicted) < 1e-12
        result.append({"beta": beta, "entropy_nats": round(predicted, 10)})
    return {"fock_states": len(many), "values": result, "low_temperature_limit": "2 ln(2)"}


def entropy_control(engine):
    cases = {}
    for text in ("120000", "300000", "01110212", "01120211"):
        state = engine.named(tuple(map(int, text)))
        start_charges = charges(engine.word(state))
        lengths = [len(state)]
        for _ in range(2):
            after = engine.forward(state, EPS)
            assert engine.equal(engine.backward(after, EPS), state)
            assert charges(engine.word(after)) == start_charges
            state = after
            lengths.append(len(state))
        cases[text] = {"charges": start_charges, "lengths": lengths,
                       "entropy_at_beta_1": [round(spectral_entropy(n, 1), 10) for n in lengths]}
    a, b = cases["120000"], cases["300000"]
    assert a["charges"] == b["charges"] and (a["lengths"][1], b["lengths"][1]) == (5, 7)
    assert a["entropy_at_beta_1"][1] < a["entropy_at_beta_1"][0] < b["entropy_at_beta_1"][1]
    assert [cases[t]["lengths"] for t in ("01110212", "01120211")] == [[8, 7, 8], [8, 7, 7]]
    return cases


def all_length_step_controls(engine):
    for n in range(2, 33):
        starts = [(3,) + (0,)*(n-1), (1, 2) + (0,)*(n-1)]
        for w, target in zip(starts, (n+1, n)):
            before = engine.named(w)
            after = engine.forward(before, EPS)
            assert charges(w) == charges(engine.word(after)) == [1, 1, 0, 0, 0, 0]
            assert len(after) == target and engine.equal(engine.backward(after, EPS), before)
        for beta in (0, 0.25, 1, 4, 20):
            assert spectral_entropy(n, beta) >= 2*n*h(2*beta) - 1e-12
    return {"sample_lengths": [2, 32], "named_forward_steps": 62,
            "general_step_lengths": ["L -> L+1", "L+1 -> L"],
            "analytic_lower_bound": "2 L h(2 beta)"}


def moments_and_coupling():
    f0, f2, f4 = log(2), 9*zeta(3)/4, 225*zeta(5)/8
    for k, expected in [(1, f2), (3, f4)]:
        assert abs(quad(lambda x: h(x)*x**k, 0, np.inf, epsabs=1e-11)[0]-expected) < 1e-10
    return {"f0": round(f0, 10), "f2": round(f2, 10), "f4": round(f4, 10),
            "g2_for_bare_h": round(pi/sqrt(2*f0), 10), "alpha2_for_bare_h": round(pi/(8*f0), 10),
            "normalization_for_CCM_example_f0_18_45": round(18.45/f0, 10)}


